namespace TypeOEngine.Typedeaf.TypeOBasic2d
{
    namespace Entities
    {
        /// <summary>Specifies how a drawable texture is rendered within its size bounds.</summary>
        public enum SizeMode
        {
            /// <summary>The texture is drawn at its natural size, clipped at the size boundaries.</summary>
            Clip,
            /// <summary>The texture is stretched to fit the entire size.</summary>
            Stretch
        }
    }
}
